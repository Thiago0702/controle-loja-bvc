# Categorias a serem geradas
categorias = [
    "Tela",
    "Bateria",
    "Tampa Traseira",
    "Doc de Carga"
]

def importar_tudo():
    conn = conectar()
    if not conn:
        print("❌ Não foi possível conectar ao Supabase.")
        return

    cursor = conn.cursor()
    total_cadastrado = 0

    print("🚀 Cadastrando Telas, Baterias, Tampas e Docs de Carga no Supabase...")

    for categoria in categorias:
        for marca, modelo in modelos_base:
            nome_produto = f"{categoria} {marca} {modelo}"
            
            cursor.execute("""
                INSERT INTO estoque (nome_produto, quantidade, qtd_minima, qtd_maxima, preco_custo, preco_venda, categoria, marca, modelo)
                VALUES (%s, 0, 1, 3, 0.0, 0.0, %s, %s, %s)
                ON CONFLICT DO NOTHING;
            """, (nome_produto, categoria, marca, modelo))
            
            total_cadastrado += 1

    conn.commit()
    cursor.close()
    conn.close()

    print("--------------------------------------------------")
    print(f"✅ CONCLUÍDO COM SUCESSO!")
    print(f"📦 Total de itens gerados e salvos: {total_cadastrado}")
    print("📋 Categorias cadastradas: Tela, Bateria, Tampa Traseira e Doc de Carga")
    print("--------------------------------------------------")

if __name__ == "__main__":
    importar_tudo()